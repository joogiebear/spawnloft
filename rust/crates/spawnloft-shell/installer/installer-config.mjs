// Writes what one Windows installer build needs beside the base tauri.conf.json, into <out dir>:
//   overlay.json            passed to `tauri build --config`
//   hooks.nsh               the template's installer_hooks: defines SPAWNLOFT_CORE_SRC, the
//                           core binary the template extracts to staging before anything else
//   core-package.json       the repository package.json with this version (core-package.mjs),
//                           shipped as resources\core\package.json
//   internal-defaults.json  shipped as resources\core\internal-defaults.json: the bundled Node
//                           core starts Rust daemons (design 2.3, until R4)
//   runtime\                the pinned Node.js (stage-runtime.mjs), shipped as resources\runtime\
//   bin\spawnloft.cmd, bin\mcctl.cmd   the command-line forwarders at 1.x's paths, which run
//                           resources\bin\spawnloft-core.exe (PLAN-2.0-REMAINING.md A4)
//
//   node installer-config.mjs <version> <pubkey file> <out dir> [--feed-http]
//
// The base tauri.conf.json stays buildable with plain `cargo build`; everything that needs a
// built core binary, a signing key or a test feed is added here. Paths in `resources` are
// relative to rust/crates/spawnloft-shell or absolute.
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { writeCorePackage } from './core-package.mjs'

import { stageRuntime, runtimeFolder } from './stage-runtime.mjs'

const args = process.argv.slice(2)
const feedHttp = args.includes('--feed-http')
const [version, pubkeyFile, outDir] = args.filter((a) => !a.startsWith('--'))
if (!version || !pubkeyFile || !outDir) {
  console.error('usage: node installer-config.mjs <version> <pubkey file> <out dir> [--feed-http]')
  process.exit(64)
}
if (process.platform !== 'win32') {
  console.error('installer-config.mjs builds the Windows installer; run it on Windows')
  process.exit(64)
}

const shell = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const core = resolve(shell, '../../target/release/spawnloft-core.exe')
if (!existsSync(core)) {
  console.error(`${core} is missing: cargo build --release -p spawnloft-core first`)
  process.exit(66)
}
const out = resolve(outDir)
mkdirSync(out, { recursive: true })

// makensis reads the include as-is: backslashes are fine, a quote would end the string
if (core.includes('"')) throw new Error(`core path has a quote: ${core}`)
const hooks = join(out, 'hooks.nsh')
// the bundled Node, and the folder name the template's held-file and cleanup rules need
const runtime = await stageRuntime({ platform: 'win32', arch: 'x64', out: join(out, 'runtime') })
writeFileSync(
  hooks,
  `; generated by installer-config.mjs for ${version}\r\n!define SPAWNLOFT_CORE_SRC "${core}"\r\n` +
    `!define SPAWNLOFT_NODE_DIR "${runtimeFolder(runtime.node)}"\r\n`,
)

// `spawnloft` and `mcctl` in a terminal, as 1.x shipped them: the core binary beside them
mkdirSync(join(out, 'bin'), { recursive: true })
const forwarder = ['@echo off', '"%~dp0spawnloft-core.exe" %*', 'exit /b %errorlevel%', ''].join('\r\n')
for (const name of ['spawnloft', 'mcctl']) writeFileSync(join(out, 'bin', `${name}.cmd`), forwarder)

// the Node core's package.json, stamped with this build's version (the repository's says 1.x)
const corePackage = writeCorePackage(version, out)

const defaults = join(out, 'internal-defaults.json')
writeFileSync(defaults, JSON.stringify({ daemon: 'rust' }, null, 2) + '\n')

const overlay = {
  version,
  bundle: {
    createUpdaterArtifacts: true,
    // the layout under the install folder is the one 1.x has (resources\bin\spawnloft-core.exe,
    // resources\core\mcctl.mjs), so task shims, server launchers and MCP configs written by
    // 1.x find the same files
    resources: {
      [core]: 'resources/bin/spawnloft-core.exe',
      '../../../mcctl.mjs': 'resources/core/mcctl.mjs',
      '../../../spawnloft.mjs': 'resources/core/spawnloft.mjs',
      [corePackage]: 'resources/core/package.json',
      '../../../src/': 'resources/core/src/',
      [defaults]: 'resources/core/internal-defaults.json',
      [join(out, 'bin', 'spawnloft.cmd')]: 'resources/bin/spawnloft.cmd',
      [join(out, 'bin', 'mcctl.cmd')]: 'resources/bin/mcctl.cmd',
      [join(out, 'runtime').replaceAll('\\', '/') + '/']: 'resources/runtime/',
    },
    windows: {
      nsis: { installerHooks: hooks },
    },
  },
  plugins: {
    updater: {
      // the plugin base64-decodes `pubkey`; accept either the base64 the CLI's .pub holds or the
      // decoded two-line minisign file (UPDATER-KEYS.md release.pub), emitting the base64 form
      pubkey: (text => (text.includes('\n') ? Buffer.from(text.trimEnd() + '\n').toString('base64') : text.trim()))(readFileSync(pubkeyFile, 'utf8')),
      windows: { installMode: 'passive' },
      // test feeds are a loopback HTTP server; a release feed is HTTPS
      ...(feedHttp ? { dangerousInsecureTransportProtocol: true } : {}),
    },
  },
}
writeFileSync(join(out, 'overlay.json'), JSON.stringify(overlay, null, 2))
console.log(`wrote ${out}\\{overlay.json,hooks.nsh,internal-defaults.json,bin,runtime} for ${version} (Node ${runtime.node})`)
